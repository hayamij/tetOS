static void graphics_map_framebuffer(uint32_t phys, uint32_t size) {
    uint32_t start = phys & ~0xFFFu;
    uint32_t end = (phys + size + 0xFFFu) & ~0xFFFu;

    for (uint32_t addr = start; addr < end; addr += 0x1000u) {
        vmm_map_page(addr, addr, PAGE_WRITE);
    }
}

