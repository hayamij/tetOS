/*
 * The backbuffer deliberately lives at a fixed high physical address
 * (0x00800000, 8 MB) to stay clear of the low 1 MB (VGA hardware memory at
 * 0xA0000-0xBFFFF, BIOS area, kernel stack, etc).  Using a static array in
 * .bss used to place it around 0x13000 which overlapped the VGA MMIO window
 * and produced horizontal stripes because some pixel writes landed in VGA
 * planes instead of RAM.
 *
 * 0x00800000 is identity-mapped by vmm_init (it maps the first 32 MB), and
 * the PMM keeps everything below PMM_RESERVED_END reserved so nothing else
 * allocates this range.
 */
#define GRAPHICS_BACKBUFFER_PHYS 0x00800000u
static uint32_t *backbuffer = (uint32_t *)GRAPHICS_BACKBUFFER_PHYS;

uint32_t *graphics_get_backbuffer_ptr(void) { return backbuffer; }

