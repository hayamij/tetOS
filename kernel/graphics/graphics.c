void graphics_init(void) {
    graphics_clear(0);
    graphics_present();
}

void graphics_clear(color_t color) {
    memset(backbuffer, color, GRAPHICS_WIDTH * GRAPHICS_HEIGHT);
}

void graphics_set_pixel(uint32_t x, uint32_t y, color_t color) {
    if (x >= GRAPHICS_WIDTH || y >= GRAPHICS_HEIGHT) return;
    backbuffer[y * GRAPHICS_WIDTH + x] = color;
}

color_t graphics_get_pixel(uint32_t x, uint32_t y) {
    if (x >= GRAPHICS_WIDTH || y >= GRAPHICS_HEIGHT) return 0;
    return backbuffer[y * GRAPHICS_WIDTH + x];
}

void graphics_present(void) {
    memcpy(framebuffer, backbuffer, GRAPHICS_WIDTH * GRAPHICS_HEIGHT);
}

void graphics_fill_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, color_t color) {
    uint32_t i, j;
    for (j = 0; j < h; j++) {
        for (i = 0; i < w; i++) {
            graphics_set_pixel(x + i, y + j, color);
        }
    }
}

void graphics_draw_line(uint32_t x0, uint32_t y0, uint32_t x1, uint32_t y1, color_t color) {
    int dx = (x1 > x0) ? (x1 - x0) : (x0 - x1);
    int dy = (y1 > y0) ? (y1 - y0) : (y0 - y1);
    int sx = (x1 > x0) ? 1 : -1;
    int sy = (y1 > y0) ? 1 : -1;
    int err = dx - dy;

    while (1) {
        graphics_set_pixel(x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 > -dy) {
            err -= dy;
            x0 += sx;
        }
        if (e2 < dx) {
            err += dx;
            y0 += sy;
        }
    }
}

void graphics_draw_char(uint32_t x, uint32_t y, char c, color_t fg, color_t bg) {
    int i, j;
    uint8_t *glyph = (uint8_t *)font_8x8[(uint8_t)c];

    for (j = 0; j < 8; j++) {
        for (i = 0; i < 8; i++) {
            if (glyph[j] & (0x80 >> i)) {
                graphics_set_pixel(x + i, y + j, fg);
            } else {
                graphics_set_pixel(x + i, y + j, bg);
            }
        }
    }
}

void graphics_draw_string(uint32_t x, uint32_t y, const char *str, color_t fg, color_t bg) {
    int i = 0;
    while (str[i]) {
        graphics_draw_char(x + i * 8, y, str[i], fg, bg);
        i++;
    }
}
